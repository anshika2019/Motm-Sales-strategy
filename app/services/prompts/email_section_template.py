EMAIL_SECTION_TEMPLATE = """📧 EMAIL

Build the email around six beats, IN ORDER. These beat names (SUBJECT,
OPENING, RELEVANCE, CAPABILITY, REFERENCE, REQUEST) are for YOUR planning
only — never print them, number them, or label any line with them in the
output.

SUBJECT (beat 1)
  Situation / application / next-step focused. Do not make the subject
  primarily about the product name.
  Wrong: "Exploring supply options for high-pressure hydraulic manifold
  blocks at [Company]" (leads with the product).
  Right: "Exploring an additional machining source for [Company]" (leads
  with the situation/next step; the product can still be named later,
  just not as the subject's main subject).

OPENING (beat 2)
  State the reason for contacting the prospect now. Reference the actual
  previous interaction when one exists, and acknowledge relevant feedback
  or the current opportunity status. Do not restart the product pitch when
  the prospect already knows the product.

RELEVANCE (beat 3)
  One line connecting this to something specific about the prospect —
  their business, persona, application, or situation. This is why THEY
  should keep reading, not a general statement about the sender.

CAPABILITY (beat 4)
  State how the sender helps — the relevant product/service capability
  and the business benefit it delivers. ALWAYS include this beat; do not
  skip straight from relevance to the ask without saying what is actually
  being offered. Keep it to what is genuinely relevant to this opportunity
  — do not restate the full product pitch when the prospect already knows
  it.

REFERENCE (beat 5)
  Include a proof point ONLY if one is explicitly available and relevant.
  This is the one beat that may be omitted — never invent a client name,
  result, or credibility statement to fill it.

REQUEST (beat 6)
  End with ONE clear next-step request. The ask must state what value the
  call or meeting offers the PROSPECT — not what the sender wants to
  discuss. Wrong: "Would you be open to compare notes on challenges?"
  Right: "Would you be open to a five-minute call to see if our capacity
  could handle your overflow requirements?"

Beats 2, 3, 4, and 6 (Opening, Relevance, Capability, Request) must always
be genuinely present. Beat 5 (Reference) is the only conditional beat —
omit it, don't fabricate it, when no real proof point exists.

Never invent facts, customer results,
specifications, certifications, savings, or case
studies. This does NOT apply to a number the
prospect or salesperson already stated in the sales
situation or previous interaction (e.g. a price gap
they quoted) -- reusing that accurately is
required, not an invented fact.

Keep total email under 120 words.

BANNED WORDS AND PHRASES:
  strong / impressive / extensive / robust / excellent / outstanding /
  exceptional / world-class / best-in-class / cutting-edge / seamless /
  "caught my attention" / "aligns closely with" /
  "expertise in delivering" / "supporting diverse sectors" /
  "Given your emphasis on innovation/quality" /
  "Given your capabilities and quality systems" /
  "compare notes" / "exchange ideas"
Do not open a sentence with "Given your..." as a bridge into the
pitch -- state the connection to the prospect directly instead. If any
banned word/phrase appears, rewrite that sentence before returning.

SENDER ACCURACY RULE:
Never describe the sender as a "manufacturer",
"fellow manufacturer", or "producer" unless the
sales situation explicitly confirms they manufacture
the product being sold. If the sender's role is not
confirmed in the situation, describe them by what
they offer ("we specialise in supplying precision
ground hydraulic spools") not by what they are
("as a fellow manufacturer"). Misrepresenting the
sender's company type destroys credibility when
the prospect searches for the company.

PEER FRAMING RULE:
Peer-to-peer framing ("as a fellow manufacturer",
"as someone who understands your challenges") is
only appropriate when the sender genuinely shares
the prospect's industry position.
If the sender is a supplier to the prospect's
industry — not a peer within it — use supplier
framing instead.
Peer (only when accurate):
  "As a manufacturer of hydraulic spools..."
Supplier (default unless confirmed otherwise):
  "We work with precision machining companies
  that need an external partner for overflow
  capacity..."
Never use peer framing when the sender is a
sales or service company representing a
manufacturer.

VERTICAL INTEGRATION WARNING:
If the company profile suggests the prospect may
manufacture the same product being sold, do NOT
write a standard sales email. Instead write a
qualification email that:
- Acknowledges their manufacturing capability
- Opens a conversation about overflow capacity,
  specialty variants, or subcontracting needs
- Does not pitch the product as if they are a
  standard buyer
Example opening for this case:
  "I noticed your team manufactures precision
  machined components in-house. We work with
  similar manufacturers who occasionally need
  an external partner for overflow or specialty
  tolerance work."

REQUIRED OUTPUT LAYOUT -- write the actual email
as separate lines/paragraphs with a blank line
between each part, exactly like a real email a
person would send, not as one run-on paragraph:

Subject: <subject line>

<greeting>,

<paragraph 1>

<paragraph 2, if needed>

<one-line next-step ask>

Regards,
<sign-off -- see SELF-INTRODUCTION RULE /
PERSONALIZATION RULE>"""
